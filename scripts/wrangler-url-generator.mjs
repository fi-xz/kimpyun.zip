/**
 * src/data/shortlinks.ts → worker/wrangler.toml [[routes]] 생성.
 *
 *   node scripts/wrangler-url-generator.mjs            생성(덮어쓰기)
 *   node scripts/wrangler-url-generator.mjs --check    최신 상태인지 검사만 (CI·빌드용)
 *
 * Node 가 .ts 를 직접 읽습니다(타입 스트리핑, Node 22.18+). 정규식으로 파싱하지 마십시오 —
 * shortlinks.ts 는 JSON 이 아니라 템플릿 리터럴·주석·후행 쉼표가 있는 TypeScript 입니다.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { shortLinks } from "../src/data/shortlinks.ts";

const WARNING = "# AUTO GENERATED BY BUILD SCRIPT, DO NOT EDIT.";

const WORKER_NAME = "kimpyunzip";
const WORKER_MAIN = "src/index.ts";
const ZONE_NAME = "kimpyun.zip";

/**
 * 고정값입니다. 실행할 때마다 오늘 날짜로 갱신하면 Worker 런타임 동작이
 * 나도 모르는 사이에 바뀝니다. 올릴 때는 변경 로그를 확인하고 의도적으로 올리십시오.
 * https://developers.cloudflare.com/workers/configuration/compatibility-dates/
 */
const COMPATIBILITY_DATE = "2026-07-12";

const OUT = fileURLToPath(new URL("../worker/wrangler.toml", import.meta.url));

/** 데이터가 라우팅으로 옮겨지기 전에 잡아야 할 것들 */
function validate(links) {
  const errors = [];
  const seen = new Map(); // path → 그 path 를 선언한 항목의 path

  for (const link of links) {
    const { path, label, listed, target, handler, aliases = [] } = link;

    if (!path.startsWith("/")) {
      errors.push(`${path}: 경로는 "/" 로 시작해야 합니다`);
    }
    if (Boolean(target) === Boolean(handler)) {
      errors.push(`${path}: target 과 handler 중 정확히 하나만 필요합니다`);
    }
    if (listed && !label.trim()) {
      errors.push(`${path}: listed: true 인데 label 이 비었습니다`);
    }

    for (const p of [path, ...aliases]) {
      if (!p.startsWith("/")) {
        errors.push(`${path}: 별칭 "${p}" 도 "/" 로 시작해야 합니다`);
      }
      if (seen.has(p)) {
        errors.push(`${p}: ${seen.get(p)} 과(와) 중복됩니다`);
      }
      seen.set(p, path);
    }
  }

  if (errors.length) {
    console.error("✖ src/data/shortlinks.ts 에 문제가 있습니다:");
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }
  return [...seen.keys()];
}

function render(paths) {
  const routes = paths
    .map(
      (p) =>
        `[[routes]]\npattern = "${ZONE_NAME}${p}"\nzone_name = "${ZONE_NAME}"\n`,
    )
    .join("\n");

  return [
    WARNING,
    "# 고치려면 src/data/shortlinks.ts 를 수정한 뒤",
    "# pnpm run worker:routes 를 실행하십시오.",
    "",
    `name = "${WORKER_NAME}"`,
    `main = "${WORKER_MAIN}"`,
    `compatibility_date = "${COMPATIBILITY_DATE}"`,
    "",
    routes,
  ].join("\n");
}

const expected = render(validate(shortLinks));
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  let actual = null;
  try {
    actual = readFileSync(OUT, "utf8");
  } catch {
    /* 파일 없음 → 아래에서 불일치로 처리 */
  }
  if (actual !== expected) {
    console.error("✖ worker/wrangler.toml 이 shortlinks.ts 와 어긋났습니다.");
    console.error("  해결: pnpm run worker:routes");
    process.exit(1);
  }
  console.log(
    `✓ worker/wrangler.toml 최신 상태 (라우트 ${validate(shortLinks).length}개)`,
  );
} else {
  writeFileSync(OUT, expected, "utf8");
  const paths = validate(shortLinks);
  console.log(`✓ worker/wrangler.toml 생성 — 라우트 ${paths.length}개`);
  console.log(`  ${paths.join(" ")}`);
}
